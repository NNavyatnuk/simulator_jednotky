import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const [html, css] = await Promise.all([
  readFile(resolve(root, 'index.html'), 'utf8'),
  readFile(resolve(root, 'src/styles.css'), 'utf8'),
]);
const styleTag = '<link rel="stylesheet" href="/src/styles.css" />';
const scriptTag = '<script type="module" src="/src/app.js"></script>';
if (!html.includes(styleTag) || !html.includes(scriptTag) || !html.includes('</body>')) {
  throw new Error('Šablona index.html se změnila; aktualizujte značky sestavení samostatného HTML.');
}
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/app.js'],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  charset: 'utf8',
});
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const output = '<!-- Generated by npm run build:standalone. Edit index.html and src/, then rebuild. -->\n' + html
  .replace(styleTag, () => `<style>\n${css}\n</style>`)
  .replace(scriptTag, '')
  // A classic script must run after the DOM, unlike the deferred source module.
  .replace('</body>', () => `<script>\n${script}\n</script>\n</body>`);
await writeFile(resolve(root, 'SPUSTIT.html'), output);
console.log('Vytvořen SPUSTIT.html — samostatný simulátor bez serveru.');
